def draw_label(path, text):
    im = Image.open(path)
    px = im.load()
    w, h = im.size
    bg = px[1, 3]
    for y in range(4, 12):
        for x in range(1, w - 1):
            px[x, y] = bg
    widths = [len(FONT[c][0]) for c in text]
    gap = 2 if sum(widths) + 2 * (len(text) - 1) <= w - 4 else 1
    total = sum(widths) + gap * (len(text) - 1)
    x0 = max(1, (w - total) // 2)
    glyph = set()
    x = x0
    for c, cw in zip(text, widths):
        for gy, row in enumerate(FONT[c]):
            for gx, ch in enumerate(row):
                if ch == '#':
                    glyph.add((x + gx, 4 + gy))
        x += cw + gap
    for (gx, gy) in glyph:
        for sx, sy in ((gx + 1, gy), (gx, gy + 1), (gx + 1, gy + 1)):
            if (sx, sy) not in glyph and 1 <= sx < w - 1 and sy <= 11:
                px[sx, sy] = 0xe
    for (gx, gy) in glyph:
        if 1 <= gx < w - 1:
            px[gx, gy] = 0xf
    im.save(path)


