def read(p):
    with open(P(p), encoding='utf-8') as f:
        return f.read()


def write(p, s):
    with open(P(p), 'w', encoding='utf-8') as f:
        f.write(s)


def atlas_types():
    with open(P('atlas', 'data', 'types.json'), encoding='utf-8') as f:
        return json.load(f)


# ---- names
src = read('src/battle_main.c')
for t, name in NAMES.items():
    src = re.sub(r'(\[TYPE_%s\] = _\(")[^"]*("\))' % t, r'\g<1>%s\g<2>' % name, src)

# ---- type chart: Living Atlas chart, entries other than 1x.
chart = atlas_types()['chart']
MUL = {2: 'TYPE_MUL_SUPER_EFFECTIVE', 0.5: 'TYPE_MUL_NOT_EFFECTIVE', 0: 'TYPE_MUL_NO_EFFECT'}
rows = []
for atk, row in chart.items():
    for dfn, m in row.items():
        if m != 1:
            rows.append('    TYPE_%s, TYPE_%s, %s,' % (LA_TO_GEN3[atk], LA_TO_GEN3[dfn], MUL[m]))
rows.append('    TYPE_FORESIGHT, TYPE_FORESIGHT, TYPE_MUL_NO_EFFECT,')
rows.append('    TYPE_ENDTABLE, TYPE_ENDTABLE, TYPE_MUL_NO_EFFECT')
table = ('// Living Atlas type chart, generated by atlas/apply_types.py.\n'
         'const u8 gTypeEffectiveness[%d] =\n{\n%s\n};' % (len(rows) * 3, '\n'.join(rows)))
src = re.sub(r'(// Living Atlas type chart[^\n]*\n)?const u8 gTypeEffectiveness\[\d+\] =\n\{[\s\S]*?\n\};', lambda m: table, src)
write('src/battle_main.c', src)

# Type names up to 7 letters (VERDANT).
g = read('include/constants/global.h')
write('include/constants/global.h', re.sub(r'#define TYPE_NAME_LENGTH \d+', '#define TYPE_NAME_LENGTH 7', g))

# ---- retype Ghost and Dragon moves
mv = read('src/data/battle_moves.h')
for move, t in RETYPE.items():
    mv = re.sub(r'(\[MOVE_%s\] =\s*\{[\s\S]*?\.type = )TYPE_\w+' % move, r'\g<1>TYPE_%s' % t, mv, count=1)
